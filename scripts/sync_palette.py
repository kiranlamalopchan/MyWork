#!/usr/bin/env python3
"""Generate web/native colours from one palette. Run with --check to detect drift."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'design/tokens/palette.json'

def css_name(name):
    return re.sub(r'([a-z])([A-Z0-9])', r'\1-\2', name).lower()

def resolve(values, name, chain=()):
    if name in chain:
        raise ValueError(f'Circular palette alias: {name}')
    value = values[name]
    return resolve(values, value[1:], (*chain, name)) if isinstance(value, str) and value.startswith('$') else value

def outputs():
    source = json.loads(SOURCE.read_text())
    if sum(section['share'] for section in source['usage'].values()) != 100:
        raise ValueError('Palette shares must total 100')
    if source['dark']['bg'] != '#000000':
        raise ValueError('Dark page background must remain pure black')
    themes = {mode: {key: resolve(source[mode], key) for key in source[mode]} for mode in ('light', 'dark')}
    native = '// Generated by scripts/sync_palette.py. Edit design/tokens/palette.json.\n'
    native += 'export const palettes = ' + json.dumps(themes, indent=2) + ';\n'
    def block(mode, indent='  '):
        return '\n'.join(f'{indent}--{css_name(key)}: {"var(--" + css_name(value[1:]) + ")" if value.startswith("$") else value};' for key, value in source[mode].items() if isinstance(value, str))
    css = '/* Generated by scripts/sync_palette.py. Edit design/tokens/palette.json. */\n'
    css += ':root {\n  color-scheme: light;\n' + block('light') + '\n}\n'
    css += '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n' + block('dark', '    ') + '\n  }\n}\n'
    css += ':root[data-theme="dark"] {\n  color-scheme: dark;\n' + block('dark') + '\n}\n'
    return {ROOT/'mobile/src/ui/palette.ts': native, ROOT/'static/css/palette.css': css}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, 'Palette output is stale: ' + ', '.join(stale) + '\nRun python scripts/sync_palette.py\n')
